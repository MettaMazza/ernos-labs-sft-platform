def _state(isotopes: tuple[str, str], record: str) -> NuclearElectronicSupport:
    return NuclearElectronicSupport(
        HeldLabel("molecular-carrier", "hydrogen-diatomic"),
        (HeldLabel("nuclear-occurrence", "left"), HeldLabel("nuclear-occurrence", "right")),
        tuple(HeldLabel("molecular-isotope", value) for value in isotopes),
        HeldLabel("molecular-electronic-support", "one-sigma-g-two"),
        HeldLabel("molecular-electronic-state", "X-singlet-sigma-g"),
        HeldLabel("nuclear-electronic-record", record),
    )


def _incomplete_rejects() -> bool:
    try:
        NuclearElectronicSupport(
            HeldLabel("molecular-carrier", "hydrogen-diatomic"),
            (HeldLabel("nuclear-occurrence", "left"), HeldLabel("nuclear-occurrence", "right")),
            (HeldLabel("molecular-isotope", "protium"),),
            HeldLabel("molecular-electronic-support", "one-sigma-g-two"),
            HeldLabel("molecular-electronic-state", "X-singlet-sigma-g"),
            HeldLabel("nuclear-electronic-record", "incomplete"),
        )
    except InadmissibleExactValue:
        return True
    return False


