@dataclass(frozen=True)
class NuclearElectronicSupport:
    molecular_carrier: HeldLabel
    nuclear_occurrences: tuple[HeldLabel, ...]
    isotope_labels: tuple[HeldLabel, ...]
    electronic_support: HeldLabel
    electronic_state: HeldLabel
    record: HeldLabel

    def __post_init__(self) -> None:
        if self.molecular_carrier.family != "molecular-carrier":
            raise InadmissibleExactValue("joint support requires one molecular carrier")
        if not self.nuclear_occurrences or len(set(self.nuclear_occurrences)) != len(self.nuclear_occurrences):
            raise InadmissibleExactValue("nuclear occurrences must be positive and distinct")
        if any(label.family != "nuclear-occurrence" for label in self.nuclear_occurrences):
            raise InadmissibleExactValue("nuclear occurrence labels have the wrong family")
        if len(self.isotope_labels) != len(self.nuclear_occurrences) or any(label.family != "molecular-isotope" for label in self.isotope_labels):
            raise InadmissibleExactValue("every nuclear occurrence retains one isotope label")
        if self.electronic_support.family != "molecular-electronic-support" or self.electronic_state.family != "molecular-electronic-state":
            raise InadmissibleExactValue("electronic support and state must both be retained")
        if self.record.family != "nuclear-electronic-record":
            raise InadmissibleExactValue("joint support requires a retained observation record")

    @property
    def nuclear_support_key(self) -> tuple[str, ...]:
        return tuple(label.label for label in self.isotope_labels)

    @property
    def electronic_support_key(self) -> tuple[str, str]:
        return self.electronic_support.label, self.electronic_state.label


def equal_electronic_support_isotopologues(left: NuclearElectronicSupport, right: NuclearElectronicSupport) -> bool:
    if left.molecular_carrier != right.molecular_carrier:
        raise InadmissibleExactValue("isotopologue comparison requires one molecular carrier class")
    return left.electronic_support_key == right.electronic_support_key and left.nuclear_support_key != right.nuclear_support_key


